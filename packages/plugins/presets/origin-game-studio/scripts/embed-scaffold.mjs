#!/usr/bin/env bun
/**
 * Embed first-party game scaffolds as a TypeScript module the plugin can write
 * through ctx.fs. Regenerated whenever assets/game-scaffold changes.
 */
import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const scaffoldRoot = join(root, "assets", "game-scaffold");
const outFile = join(root, "src", "scaffold", "embedded.ts");

async function collect(dir) {
	const entries = await readdir(dir, { withFileTypes: true });
	const files = [];
	for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) {
			files.push(...(await collect(full)));
			continue;
		}
		files.push({
			relative: relative(scaffoldRoot, full).split("\\").join("/"),
			content: await readFile(full, "utf8"),
		});
	}
	return files;
}

const files = await collect(scaffoldRoot);
await mkdir(dirname(outFile), { recursive: true });
const body = files
	.map(
		(file) =>
			`\t${JSON.stringify(file.relative)}: ${JSON.stringify(file.content)},`,
	)
	.join("\n");

const source = `/* Generated by scripts/embed-scaffold.mjs — do not edit. */\n/* biome-ignore-all lint: generated scaffold payload */\nexport const SCAFFOLD_FILES: Readonly<Record<string, string>> = {\n${body}\n};\n`;
await writeFile(outFile, source);
console.log(`embedded ${files.length} scaffold files → src/scaffold/embedded.ts`);
